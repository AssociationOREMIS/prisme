import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const dirname = path.dirname(fileURLToPath(import.meta.url))
const registryPath = path.resolve(dirname, '../src/components/registry.ts')
const outputPath = path.resolve(dirname, '../src/components/paths.generated.ts')

const source = fs.readFileSync(registryPath, 'utf8')
const importRe = /^import\s*\{([^}]+)\}\s*from\s*'\.\/([^']+)'/gm

const paths = {}
for (const match of source.matchAll(importRe)) {
  const names = match[1]
    .split(',')
    .map((name) => name.trim())
    .filter(Boolean)
  const relativePath = match[2]

  for (const name of names) {
    paths[name] = `@oremis/prisme/components/${relativePath}`
  }
}

const entries = Object.keys(paths)
  .sort()
  .map((name) => `  ${name}: '${paths[name]}',`)
  .join('\n')

const output = `// Generated by scripts/generate-component-paths.mjs from src/components/registry.ts.
// Do not edit by hand — run \`npm run generate:paths\` to regenerate.

/**
 * Maps every public component's \`PrXxx\` name to the package subpath that
 * exports it on its own, for consumers that want to import a single
 * component without pulling in the rest of Prisme.
 */
export const componentPaths: Record<string, string> = {
${entries}
}
`

fs.writeFileSync(outputPath, output)
